'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={URL,Map,Set};context.window=context;vm.createContext(context);
for(const file of ['web/tracking-day-data.js','web/tracking-context.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context);
const tools=context.HotTurkeyTrackingContext;
const row={id:'first',timeline:'documents',title:'Page',url:'https://example.org/a?b=1',start:10,end:20};
const web={title:'example.org',rows:[row],ranges:[[10,20]]};
assert.equal(tools.resource(web).value,row.url);
assert(tools.options(web).some(item=>item.id==='open'));
assert(!tools.options(web).some(item=>item.id==='reveal'));
const file={...web,rows:[{...row,url:'file:///tmp/report%20file.pdf'}]};
assert.equal(tools.resource(file).value,'/tmp/report file.pdf');
assert(tools.options(file).some(item=>item.id==='reveal'));
for(const url of ['javascript:alert(1)','https://user:secret@example.org/','edge://newtab/'])assert.equal(tools.resource({...web,rows:[{...row,url}]}),null);
const merged={...web,rows:[{...row,activity_ids:['first','second']},{...row,id:'clip',original_id:'first',start:20,end:30}]};
const records=JSON.parse(JSON.stringify(tools.records(merged)));
assert.deepEqual(records,[{timeline:'documents',id:'first',ranges:[[10,30]]},{timeline:'documents',id:'second',ranges:[[10,20]]}]);
const group={title:'Editor',group:{},rows:[{...row,timeline:'applications',url:''}],ranges:[[10,20]]};
assert.equal(tools.resource(group),null);
assert(tools.options(group).some(item=>item.id==='color'));
assert(!tools.options({...group,rows:[{...row,timeline:'autotags'}]}).some(item=>item.id==='delete'));
assert.equal(tools.query({...web,row:{domain:'example.org'}}),'url:#"^https?://(?:[^/]+\\.)?example\\.org(?::[0-9]+)?(?:[/?#]|$)"');
assert(tools.query(web).includes('a\\?b=1'));
console.log('Context menu resource safety, contextual actions and exact record identity checks passed');
